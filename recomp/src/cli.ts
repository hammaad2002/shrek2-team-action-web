/**
 * Recompiler CLI.
 *   node recomp/src/cli.ts gen-c <exe> --out <dir> [--hints research/ghidra-functions.json] [--per-file 200] [--only 0xADDR,...]
 *   node recomp/src/cli.ts metadata <exe> --hints research/ghidra-functions.json --out metadata/<sha256>.json
 *   node recomp/src/cli.ts gen-wasm <exe> --meta metadata/<sha256>.json --out <dir>
 *
 * gen-c / gen-wasm output contains translated game code: write it under work/ only, never commit
 * or deploy it. Metadata holds only addresses (function entries, jump-table targets).
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { Program } from "./cfg.ts";
import { emitFunction, emitPrototypes } from "./emit-c.ts";
import { buildMetadata, translateExe, type ExeMetadata } from "./translate.ts";
import { loadGhidraHints } from "./hints.ts";
import { liftFunction } from "./lift.ts";
import { PeImage } from "./pe.ts";

const args = process.argv.slice(2);
const cmd = args[0];
const opt = (name: string) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);

if (cmd !== "gen-c" && cmd !== "gen-wasm" && cmd !== "metadata") {
  console.error("usage: node recomp/src/cli.ts gen-c|gen-wasm|metadata <exe> --out <path> [--hints file] [--meta file] [--per-file N] [--only addrs]");
  process.exit(2);
}
const exe = args[1];
if (cmd === "gen-wasm") {
  const meta = JSON.parse(readFileSync(opt("--meta")!, "utf8")) as ExeMetadata;
  const bytes = new Uint8Array(readFileSync(exe));
  const sha = createHash("sha256").update(bytes).digest("hex");
  if (sha !== meta.exe.sha256) throw new Error(`executable ${sha} does not match metadata ${meta.exe.sha256}`);
  const out = opt("--out") ?? "work/gen-wasm";
  mkdirSync(out, { recursive: true });
  const res = translateExe(bytes, meta);
  writeFileSync(join(out, "game.wasm"), res.wasm);
  console.log(
    `translated ${res.functions} functions: discovery ${res.ms.discover.toFixed(0)} ms, translation ${res.ms.translate.toFixed(0)} ms, ` +
      `${(res.wasm.length / 1048576).toFixed(1)} MB (${res.irreducible} irreducible)`,
  );
  process.exit(0);
}
const out = opt("--out") ?? "work/gen-c";
const perFile = Number(opt("--per-file") ?? 200);
const pe = new PeImage(new Uint8Array(readFileSync(exe)));
const hintsPath = opt("--hints");
const hints = hintsPath ? await loadGhidraHints(hintsPath) : undefined;
const t0 = performance.now();
const prog = new Program(pe, hints ?? {});
prog.discover();
const t1 = performance.now();

const importIndex = new Map(pe.imports.map((im, i) => [im.iatSlot, i]));
const entries = [...prog.funcs.keys()].sort((a, b) => a - b);
const only = opt("--only")?.split(",").map((s) => Number.parseInt(s, 16));
const selected = only ? entries.filter((e) => only.includes(e)) : entries;

if (cmd === "metadata") {
  const bytes = new Uint8Array(readFileSync(exe));
  const sha = createHash("sha256").update(bytes).digest("hex");
  const meta = buildMetadata(prog, { name: basename(exe), sha256: sha, size: bytes.length });
  const path = opt("--out") ?? `metadata/${sha}.json`;
  writeFileSync(path, JSON.stringify(meta) + "\n");
  console.log(`metadata: ${meta.entries.length} functions, ${meta.noreturn.length} no-return, ${meta.jumpTargets.length} jump tables -> ${path}`);
  process.exit(0);
}
mkdirSync(out, { recursive: true });
const header = [
  "/* Generated by shrek2web recomp. Contains translated game code: never commit or distribute. */",
  '#include "recomp.h"',
  '#include "recomp_funcs.h"',
  "",
].join("\n");
let traps = 0;
const trapKinds = new Map<string, number>();
let lines = 0;
for (let k = 0; k * perFile < selected.length; k++) {
  const chunk = selected.slice(k * perFile, (k + 1) * perFile);
  const parts: string[] = [header];
  for (const e of chunk) {
    const ir = liftFunction(prog, prog.funcs.get(e)!, (slot) => importIndex.get(slot)!);
    for (const b of ir.blocks.values())
      for (const s of b.stmts)
        if (s.k === "trap" && s.msg.startsWith("unsupported")) {
          traps++;
          const key = s.msg.replace(/ at 0x[0-9a-f]+.*$/, "").replace(/^unsupported [^:]*?: /, "").slice(0, 60);
          const mn = s.msg.split(" ")[1];
          trapKinds.set(mn + " | " + key, (trapKinds.get(mn + " | " + key) ?? 0) + 1);
        }
    const text = emitFunction(ir);
    lines += text.split("\n").length;
    parts.push(text, "");
  }
  writeFileSync(join(out, `funcs_${String(k).padStart(3, "0")}.c`), parts.join("\n"));
}
{
  const starts = new Set<number>();
  for (const f of prog.funcs.values()) for (const b of f.blocks.keys()) starts.add(b);
  writeFileSync(join(out, "blocks.bin"), new Uint8Array(Uint32Array.from([...starts].sort((a, b) => a - b)).buffer));
}
writeFileSync(join(out, "recomp_funcs.h"), `#pragma once\n#include "recomp.h"\n${emitPrototypes(entries)}\n`);
writeFileSync(
  join(out, "recomp_table.c"),
  [
    header,
    "const GuestFnEntry recomp_functions[] = {",
    ...selected.map((e) => `  { 0x${e.toString(16)}u, f_${e.toString(16).padStart(8, "0")} },`),
    "};",
    `const uint32_t recomp_function_count = ${selected.length};`,
    "",
  ].join("\n"),
);
writeFileSync(
  join(out, "imports.json"),
  JSON.stringify(pe.imports.map((im, i) => ({ index: i, dll: im.dll, name: im.name, slot: im.iatSlot })), null, 1),
);
const t2 = performance.now();
console.log(`discovery ${(t1 - t0).toFixed(0)} ms; lifted+emitted ${selected.length} functions (${lines} lines) in ${(t2 - t1).toFixed(0)} ms`);
console.log(`unsupported-instruction traps: ${traps}`);
console.log([...trapKinds.entries()].sort((a, b) => b[1] - a[1]).slice(0, 40).map(([k, v]) => `  ${v}\t${k}`).join("\n"));
